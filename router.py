def detect_route(message: str) -> str:
    text = message.strip().lower()

    # =====================================================
    # 1. 取消目前流程
    # =====================================================

    cancel_keywords = [
        "取消",
        "算了",
        "不要了",
        "停止",
        "重新開始"
    ]

    if any(keyword in text for keyword in cancel_keywords):
        return "cancel"

    # =====================================================
    # 2. 知識 / 說明型問題
    # =====================================================

    knowledge_patterns = [
        "什麼是",
        "是什麼",
        "什麼意思",
        "怎麼運作",
        "原理",
        "有什麼作用",
        "有什麼效果",
        "有什麼好處",
        "為什麼",
        "介紹一下",
        "解釋",
        "告訴我什麼是",

        # 適用性問題
        "適合嗎",
        "適不適合",
        "適合什麼",
        "適合哪些",
        "什麼時候適合",
    ]

    if any(pattern in text for pattern in knowledge_patterns):
        return "knowledge"

    # =====================================================
    # 2. 呼吸
    # =====================================================

    breathing_keywords = [
        "呼吸",
        "呼吸練習",
        "breathing"
    ]

    if any(keyword in text for keyword in breathing_keywords):
        return "breathing"


    # =====================================================
    # 3. 穴位 / 身體放鬆
    # =====================================================

    acupressure_keywords = [
        # 功能入口
        "穴位",
        "穴位放鬆",
        "身體放鬆",
        "身體疲勞",
        "按摩",

        # 頭部
        "頭部緊繃",
        "頭很緊",
        "眼睛疲勞",
        "眼睛很累",
        "精神疲勞",
        "腦袋停不下來",

        # 肩頸
        "肩頸",
        "肩膀",
        "肩膀僵硬",
        "脖子",
        "脖子緊繃",
        "久坐後不舒服",
        "肩頸緊繃",

        # 手部
        "手腕",
        "手腕痠",
        "手腕酸",
        "手指疲勞",
        "手很累",
        "滑手機",
        "打字",

        # 常見身體不適
        "痠痛",
        "酸痛"
    ]

    if any(keyword in text for keyword in acupressure_keywords):
        return "acupressure"


    # =====================================================
    # 4. App 使用說明
    # =====================================================

    app_help_keywords = [
        "app怎麼用",
        "app 怎麼用",
        "怎麼使用",
        "如何使用",
        "功能介紹",
        "使用方法"
    ]

    if any(keyword in text for keyword in app_help_keywords):
        return "app_help"


    # =====================================================
    # 5. 冥想
    # =====================================================

    meditation_keywords = [
        # 功能入口
        "幫我推薦",
        "推薦",
        "冥想",

        # 使用者可能直接描述需求
        "放鬆",
        "睡覺",
        "睡眠",
        "專注",
        "放空",
        "安撫"
    ]

    if any(keyword in text for keyword in meditation_keywords):
        return "meditation"


    # =====================================================
    # 6. 一般聊天
    # =====================================================

    return "general_chat"